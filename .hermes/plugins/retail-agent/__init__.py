from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any, Callable


PROJECT_ROOT = Path(__file__).resolve().parents[3]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from retail_agent import tools  # noqa: E402


def _handler(fn: Callable[..., dict[str, Any]]) -> Callable[..., str]:
    def wrapped(params: dict[str, Any], **kwargs: Any) -> str:
        del kwargs
        return json.dumps(fn(**params), sort_keys=True)

    return wrapped


def register(ctx):
    ctx.register_tool(
        name="retail_verify_customer",
        toolset="retail_agent",
        description="Verify a retail customer before touching any order.",
        schema={
            "name": "retail_verify_customer",
            "description": "Verify a customer by email and current verification ZIP/postal code. Returns customer_id on success.",
            "parameters": {
                "type": "object",
                "properties": {
                    "email": {"type": "string", "description": "Customer email on the order."},
                    "verification_postal_code": {
                        "type": "string",
                        "description": "Current ZIP/postal code used to verify the customer.",
                    },
                },
                "required": ["email", "verification_postal_code"],
            },
        },
        handler=_handler(tools.verify_customer),
    )

    ctx.register_tool(
        name="retail_locate_order",
        toolset="retail_agent",
        description="Locate the verified customer's modifiable order.",
        schema={
            "name": "retail_locate_order",
            "description": "Locate a placed or processing order for a verified customer. Rejects orders owned by another customer.",
            "parameters": {
                "type": "object",
                "properties": {
                    "customer_id": {"type": "string", "description": "Verified customer_id from retail_verify_customer."},
                    "order_id": {
                        "type": "string",
                        "description": "Optional order id such as ORD-1001. If omitted, finds the newest open order.",
                    },
                },
                "required": ["customer_id"],
            },
        },
        handler=_handler(tools.locate_order),
    )

    ctx.register_tool(
        name="retail_update_shipping_address",
        toolset="retail_agent",
        description="Safely update a verified customer's order and profile shipping address.",
        schema={
            "name": "retail_update_shipping_address",
            "description": (
                "Update shipping address only after customer verification and order ownership check. "
                "Requires customer_id from verification and an order_id located for that customer."
            ),
            "parameters": {
                "type": "object",
                "properties": {
                    "customer_id": {"type": "string"},
                    "order_id": {"type": "string"},
                    "street": {"type": "string"},
                    "city": {"type": "string"},
                    "state": {"type": "string", "description": "Two-letter US state."},
                    "postal_code": {"type": "string"},
                    "country": {"type": "string", "description": "Country code, usually US."},
                },
                "required": ["customer_id", "order_id", "street", "city", "state", "postal_code"],
            },
        },
        handler=_handler(tools.update_shipping_address),
    )

    ctx.register_tool(
        name="retail_read_order",
        toolset="retail_agent",
        description="Read an order snapshot for confirmation or evaluation.",
        schema={
            "name": "retail_read_order",
            "description": "Read a retail order by id.",
            "parameters": {
                "type": "object",
                "properties": {"order_id": {"type": "string"}},
                "required": ["order_id"],
            },
        },
        handler=_handler(tools.read_order),
    )

    ctx.register_tool(
        name="retail_get_audit_trace",
        toolset="retail_agent",
        description="Return audit events generated by the retail tools.",
        schema={
            "name": "retail_get_audit_trace",
            "description": "Return ordered audit events for the active retail demo database.",
            "parameters": {"type": "object", "properties": {}},
        },
        handler=_handler(tools.get_audit_trace),
    )
